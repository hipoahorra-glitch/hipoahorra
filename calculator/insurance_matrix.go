package calculator

import (
	"strconv"
	"strings"
)

var nnFallecimientoTariff = parseNNFallecimientoTariff()

func parseNNFallecimientoTariff() map[int][]float64 {
	rows := make(map[int][]float64)
	for _, line := range strings.Split(nnFallecimientoTable, "\n") {
		values := strings.Fields(line)
		if len(values) < 16 || values[0] == "Edad" {
			continue
		}
		age, err := strconv.Atoi(values[0])
		if err != nil {
			continue
		}
		premiums := make([]float64, 15)
		for index, value := range values[1:] {
			premium, _ := strconv.ParseFloat(strings.Replace(value, ",", ".", 1), 64)
			premiums[index] = premium
		}
		rows[age] = premiums
	}
	return rows
}

func nnFallecimientoPremium(capital float64, age int) float64 {
	const firstAge = 18
	const lastAge = 59
	if age <= firstAge {
		return interpolateCapital(capital, tariffCapitals, nnFallecimientoTariff[firstAge])
	}
	if age >= lastAge {
		return interpolateCapital(capital, tariffCapitals, nnFallecimientoTariff[lastAge])
	}
	lowerAge := age
	upperAge := age + 1
	lower := interpolateCapital(capital, tariffCapitals, nnFallecimientoTariff[lowerAge])
	upper := interpolateCapital(capital, tariffCapitals, nnFallecimientoTariff[upperAge])
	return lower + (upper-lower)*float64(age-lowerAge)/float64(upperAge-lowerAge)
}

